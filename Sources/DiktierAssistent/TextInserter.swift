import AppKit

/// Schreibt Text in die Zwischenablage und simuliert Cmd+V, um ihn in die
/// zuvor fokussierte Anwendung einzufügen. Benötigt Bedienungshilfen-Zugriff.
///
/// Was vorher in der Zwischenablage lag, kommt danach zurück: Nach
/// `restoreDelay` wird der alte Inhalt wiederhergestellt, sofern in der
/// Zwischenzeit nichts anderes hineinkopiert wurde. Zu frühes Zurücklegen
/// würde die Ziel-App den alten Inhalt einfügen lassen, spätes kostet nichts,
/// deshalb großzügig bemessen (Blitztext wartet mindestens eine Sekunde).
final class TextInserter {
    private let vKeyCode: CGKeyCode = 9 // kVK_ANSI_V
    private let restoreDelay: TimeInterval = 1.5

    /// Kennzeichnung nach nspasteboard.org: Verlaufs-Werkzeuge für die
    /// Zwischenablage übergehen Einträge mit diesen Typen.
    private let transientTypes = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    func insert(_ text: String) {
        let pasteboard = NSPasteboard.general
        let saved = snapshot(of: pasteboard)

        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for type in transientTypes { item.setString("", forType: type) }
        _ = pasteboard.writeObjects([item])
        let ourChange = pasteboard.changeCount

        guard let source = CGEventSource(stateID: .combinedSessionState),
              let keyDown = CGEvent(keyboardEventSource: source, virtualKey: vKeyCode, keyDown: true),
              let keyUp = CGEvent(keyboardEventSource: source, virtualKey: vKeyCode, keyDown: false)
        else { return }

        keyDown.flags = .maskCommand
        keyUp.flags = .maskCommand

        keyDown.post(tap: .cghidEventTap)
        keyUp.post(tap: .cghidEventTap)

        guard let saved, !saved.isEmpty else { return }
        DispatchQueue.main.asyncAfter(deadline: .now() + restoreDelay) {
            // Hat inzwischen jemand anderes kopiert, bleibt das Neuere stehen.
            guard pasteboard.changeCount == ourChange else { return }
            pasteboard.clearContents()
            _ = pasteboard.writeObjects(saved)
        }
    }

    /// Legt Text dauerhaft in die Zwischenablage, ohne einzufügen und ohne
    /// später etwas zurückzulegen.
    func copy(_ text: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
    }

    /// Eine Kopie aller Einträge mit allen Typen. Leere Liste, wenn die
    /// Zwischenablage leer war; nil, wenn sich ein Typ nicht lesen ließ, dann
    /// wird lieber nichts zurückgelegt als etwas Unvollständiges.
    private func snapshot(of pasteboard: NSPasteboard) -> [NSPasteboardItem]? {
        guard let items = pasteboard.pasteboardItems else { return [] }
        var copies: [NSPasteboardItem] = []
        for item in items {
            let copy = NSPasteboardItem()
            for type in item.types {
                guard let data = item.data(forType: type) else { return nil }
                copy.setData(data, forType: type)
            }
            copies.append(copy)
        }
        return copies
    }
}
